import { Link, useParams } from "react-router-dom";
import { ArrowLeft, Printer } from "lucide-react";
import { Button } from "../components/ui/button";
import { Field, SimBadge } from "../components/kit";
import { Logo } from "../components/AppShell";
import { useFetch } from "../lib/api";
import { inr, dt } from "../lib/format";

export default function ReceiptPage() {
  const { no } = useParams();
  const { data, error } = useFetch(`/admin/receipts/${no}`);
  if (error) return <p className="p-8 text-sm text-red-600">{error}</p>;
  if (!data) return null;
  const r = data.receipt;
  const s = data.settings;
  return (
    <div className="min-h-screen bg-[#F8FAFC] p-6 print:bg-white">
      <div className="no-print mx-auto mb-4 flex max-w-xl justify-between">
        <Link to={`/requests/${r.payment_id}`} className="inline-flex items-center gap-1 text-xs text-slate-500"><ArrowLeft className="h-3.5 w-3.5" />Back</Link>
        <Button size="sm" onClick={() => window.print()} className="bg-[#111827]" data-testid="receipt-print-btn"><Printer className="mr-1.5 h-4 w-4" />Download / Print</Button>
      </div>
      <div className="mx-auto max-w-xl rounded-xl border border-[#E2E8F0] bg-white p-8" data-testid="receipt-card">
        <div className="flex items-start justify-between"><Logo brand={s} /><SimBadge show={r.is_simulated} /></div>
        <div className="mt-8 text-[11px] font-semibold uppercase tracking-wider text-slate-400">Payment receipt</div>
        <div className="font-mono text-lg font-bold" data-testid="receipt-number">{r.receipt_no}</div>
        <div className="my-6 rounded-lg bg-[#111827] p-5 text-white">
          <div className="text-xs text-[#94A3B8]">Amount received</div>
          <div className="font-mono text-3xl font-bold text-[#B9F36B]" data-testid="receipt-amount">{inr(r.amount)}</div>
        </div>
        <div className="grid grid-cols-2 gap-4">
          <Field k="Driver" v={`${r.driver_name} (${r.driver_id})`} /><Field k="Vehicle" v={r.vehicle_reg} mono />
          <Field k="City" v={r.city} /><Field k="Issued" v={dt(r.issued_at)} />
          <Field k="Bank UTR" v={r.utr} mono /><Field k="Payment ID" v={r.payment_id} mono />
          <Field k="Provider / method" v={`${r.provider} · ${r.method}`} /><Field k="Transaction" v={r.transaction_id} mono />
          <Field k="Rental component" v={inr(r.rental_amount)} mono /><Field k="Outstanding component" v={inr(r.outstanding_amount)} mono />
        </div>
        <p className="mt-8 border-t border-[#F1F5F9] pt-4 text-[11px] text-slate-400">
          {r.is_simulated ? "SIMULATED receipt generated by the mock provider — not a record of real money. " : "Issued after verified bank/provider confirmation. "}
          {s.support_contact}
        </p>
      </div>
    </div>
  );
}
